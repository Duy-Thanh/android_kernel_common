# Generates test_loader_lskel.h from progs/test_loader.c using clang and bpftool.

set -e

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
KERNEL_ROOT="$(cd "$DIR/../../../../.." && pwd)"

CLANG="${CLANG:-$KERNEL_ROOT/prebuilts/clang/host/linux-x86/clang-r614150/bin/clang}"
if [ ! -x "$CLANG" ]; then
    CLANG="$(command -v clang || true)"
fi
if [ -z "$CLANG" ] || [ ! -x "$CLANG" ]; then
    echo "Error: clang compiler not found" >&2
    exit 1
fi

BPFTOOL="${BPFTOOL:-$(command -v bpftool || true)}"
if [ -z "$BPFTOOL" ] || [ ! -x "$BPFTOOL" ]; then
    echo "Error: bpftool not found in PATH" >&2
    exit 1
fi

TMP_OBJ="$(mktemp /tmp/test_loader.XXXXXX.o)"
TMP_SKEL="$(mktemp /tmp/test_loader.XXXXXX.h)"
trap 'rm -f "$TMP_OBJ" "$TMP_SKEL"' EXIT

"$CLANG" -target bpf -g -O2 -c "$DIR/progs/test_loader.c" -o "$TMP_OBJ"
"$BPFTOOL" gen skeleton -L "$TMP_OBJ" > "$TMP_SKEL"

cat << 'EOF' > "$DIR/test_loader_lskel.h"
/* SPDX-License-Identifier: GPL-2.0 */
/*
 * AUTOGENERATED BY generate_lskel.sh - DO NOT EDIT DIRECTLY.
 *
 * Generated from progs/test_loader.c via bpftool gen skeleton -L.
 */
#ifndef __TEST_LOADER_LSKEL_H__
#define __TEST_LOADER_LSKEL_H__

#include <stdint.h>

struct bpf_map_desc {
	int map_fd;
	uint32_t max_entries;
	uint64_t initial_value;
};

struct bpf_prog_desc {
	int prog_fd;
};

struct bpf_loader_ctx {
	uint32_t sz;
	uint32_t flags;
	uint32_t log_level;
	uint32_t log_size;
	uint64_t log_buf;
};

struct test_loader_lskel {
	struct bpf_loader_ctx ctx;
	struct {
		struct bpf_map_desc test_map;
	} maps;
	struct {
		struct bpf_prog_desc probe;
	} progs;
	struct {
		int probe_fd;
	} links;
};

EOF

awk '
/opts_data\[\]/ {
	in_data = 1
	sub(/^.*opts_data\[\][^="]*=\s*"/, "")
	printf "static const char test_loader_opts_data[] __attribute__((__aligned__(8))) = \""
}
in_data {
	if (index($0, "\";") > 0) {
		sub(/";.*/, "")
		print $0 "\";"
		print "static const size_t test_loader_opts_data_sz = sizeof(test_loader_opts_data) - 1;\n"
		in_data = 0
	} else {
		print $0
	}
}
/opts_insn\[\]/ {
	in_insn = 1
	sub(/^.*opts_insn\[\][^="]*=\s*"/, "")
	printf "static const char test_loader_opts_insn[] __attribute__((__aligned__(8))) = \""
}
in_insn {
	if (index($0, "\";") > 0) {
		sub(/";.*/, "")
		print $0 "\";"
		print "static const size_t test_loader_opts_insn_sz = sizeof(test_loader_opts_insn) - 1;\n"
		in_insn = 0
	} else {
		print $0
	}
}
' "$TMP_SKEL" >> "$DIR/test_loader_lskel.h"

echo "#endif /* __TEST_LOADER_LSKEL_H__ */" >> "$DIR/test_loader_lskel.h"
echo "Generated $DIR/test_loader_lskel.h successfully."
